import os, re, json, base64, io, sys
from PIL import Image, ImageOps, ImageStat
ROOT='/Users/william/Desktop/Mygallery'
SRC=ROOT+'/assets/img'; OUT=ROOT+'/assets/photos'
os.makedirs(OUT,exist_ok=True)
# Not shown: a UI screenshot, the favicon, and exact/near duplicates of other files.
skip={'matrix.png','favicon.png','liulimain.webp','yihe.webp','jpg-1-2 2.webp'}
files=sorted(f for f in os.listdir(SRC) if f.endswith('.webp') and f not in skip)
BASE=[480,960,1600,2400]
meta={}
for f in files:
    # URL-safe id: lower case, spaces and other symbols become '-'.
    pid=re.sub(r'[^a-z0-9_-]+','-',os.path.splitext(f)[0].lower()).strip('-')
    im=Image.open(os.path.join(SRC,f)); im=ImageOps.exif_transpose(im).convert('RGB')
    w,h=im.size; ar=w/h
    widths=[x for x in BASE if x<w]
    if ar>=2.0:  # panoramas: size by height so tall renders stay sharp
        widths=sorted(set(widths+[x for x in (3200,4800,6400,8000) if x<w]))
    widths.append(w) if (not widths or w-widths[-1]>200) else None
    widths=sorted(set(widths))
    for tw in widths:
        p=f'{OUT}/{pid}-{tw}.webp'
        if tw==w:  # full size: the site reads the original in assets/img directly (no copy)
            if os.path.exists(p): os.remove(p)
            continue
        if not os.path.exists(p):
            th=round(h*tw/w)
            im.resize((tw,th),Image.LANCZOS).save(p,'WEBP',quality=80 if tw>1000 else 78,method=6)
    t=im.copy(); t.thumbnail((32,32)); b=io.BytesIO(); t.save(b,'WEBP',quality=50)
    c=ImageStat.Stat(im.resize((64,64))).mean
    lum=sum(x*y for x,y in zip(c,(0.2126,0.7152,0.0722)))/255
    meta[pid]={'w':w,'h':h,'src':f,'sizes':widths,'lqip':'data:image/webp;base64,'+base64.b64encode(b.getvalue()).decode(),'color':'#%02x%02x%02x'%tuple(int(x) for x in c),'lum':round(lum,3)}
    print(pid,w,h,widths)
with open(ROOT+'/js/data/meta.js','w') as fh:
    fh.write('// Generated by tools/process_images.py — image dimensions, available widths, blur placeholders.\nexport default '+json.dumps(meta,separators=(',',':'))+';\n')
