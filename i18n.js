    const textSource = new WeakMap();
    const attrSource = new WeakMap();
    let titleSource = document.title;

    const normalize = (value) => value.replace(/\s+/g, " ").trim();
    const getLanguage = () => {
        try {
            const stored = window.localStorage.getItem(storageKey);
            return languages[stored] ? stored : defaultLanguage;
        } catch {
            return defaultLanguage;
        }
    };

    const translate = (source, language) => {
        if (language === defaultLanguage) {
            return source;
        }

        const table = translations[language] || {};
        return table[source] || table[normalize(source)] || source;
    };

    const applyTextNode = (node, language) => {
        const raw = node.nodeValue || "";
        const trimmed = raw.trim();

        if (!trimmed) {
            return;
        }

        if (!textSource.has(node)) {
            textSource.set(node, normalize(trimmed));
        }

        const source = textSource.get(node);
        const translated = translate(source, language);
        node.nodeValue = raw.replace(trimmed, translated);
    };

    const applyAttribute = (element, attr, language) => {
        if (!element.hasAttribute(attr)) {
            return;
        }

        let elementAttrs = attrSource.get(element);

        if (!elementAttrs) {
            elementAttrs = {};
            attrSource.set(element, elementAttrs);
        }

        if (!elementAttrs[attr]) {
            elementAttrs[attr] = element.getAttribute(attr);
        }

        element.setAttribute(attr, translate(elementAttrs[attr], language));
    };

    const syncLanguageButtons = (language) => {
        document.querySelectorAll("[data-language-choice]").forEach((button) => {
            const isActive = button.dataset.languageChoice === language;
            button.classList.toggle("is-active", isActive);
            button.setAttribute("aria-pressed", String(isActive));
        });
    };

    const applyLanguage = (language) => {
        const safeLanguage = languages[language] ? language : defaultLanguage;
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
            acceptNode(node) {
                const parent = node.parentElement;

                if (!parent || parent.closest("[data-i18n-dynamic]") || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        });

        const nodes = [];
        let node = walker.nextNode();

        while (node) {
            nodes.push(node);
            node = walker.nextNode();
        }

        nodes.forEach((textNode) => applyTextNode(textNode, safeLanguage));

        document.querySelectorAll("[placeholder], [aria-label], [alt], meta[name='description'], meta[property='og:title'], meta[property='og:description'], meta[name='twitter:title'], meta[name='twitter:description']").forEach((element) => {
            if (element.closest && element.closest("[data-i18n-dynamic]")) {
                return;
            }

            applyAttribute(element, "placeholder", safeLanguage);
            applyAttribute(element, "aria-label", safeLanguage);
            applyAttribute(element, "alt", safeLanguage);
            applyAttribute(element, "content", safeLanguage);
        });

        document.title = translate(titleSource, safeLanguage);
        document.documentElement.lang = languages[safeLanguage].htmlLang;
        syncLanguageButtons(safeLanguage);
        window.dispatchEvent(new CustomEvent("galleryw:languagechange", { detail: { language: safeLanguage } }));
    };

    const setLanguage = (language) => {
        const safeLanguage = languages[language] ? language : defaultLanguage;

        try {
            window.localStorage.setItem(storageKey, safeLanguage);
        } catch {
            return;
        }

        applyLanguage(safeLanguage);
    };

    document.addEventListener("DOMContentLoaded", () => {
        document.querySelectorAll("[data-language-choice]").forEach((button) => {
            button.addEventListener("click", () => setLanguage(button.dataset.languageChoice));
        });

        applyLanguage(getLanguage());
    });

    window.addEventListener("storage", (event) => {
        if (event.key === storageKey) {
            applyLanguage(getLanguage());
        }
    });

    window.gallerywI18n = {
        languages,
        getLanguage,
        setLanguage,
        applyLanguage,
        t(source, language = getLanguage()) {
            return translate(source, language);
        }
    };
